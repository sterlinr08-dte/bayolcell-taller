-- Formulario de financiamiento como PÁGINA WEB de Bayol (dueño, 24-oct-2026: «Hazlo» tras probar la demo).
-- El empleado manda un enlace por el chat; el cliente llena solicitud.html; la respuesta entra por la función
-- whatsapp-flow-financiamiento (acciones web_leer / web_enviar) y aparece en el CRM igual que la del Flow nativo.
-- Ya aplicado en producción con execute_sql el 24-oct-2026.

alter table public.fin_solicitudes_whatsapp
  add column if not exists canal text not null default 'flow',
  add column if not exists token text unique,
  add column if not exists vence_en timestamptz,
  add column if not exists numero integer generated by default as identity;

comment on column public.fin_solicitudes_whatsapp.canal is 'flow = formulario nativo de WhatsApp (Meta Flow); web = página solicitud.html de bayolcell.com enviada por enlace.';
comment on column public.fin_solicitudes_whatsapp.token is 'Llave aleatoria del enlace de la página web (canal web). Un solo uso: se consume al responder.';
comment on column public.fin_solicitudes_whatsapp.numero is 'Número corto de solicitud que ve el cliente («Solicitud No. 231»).';
